SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE r.name = 'ADMIN'
   OR p.name IN ('DESTINATION_READ', 'PLACE_READ', 'REVIEW_CREATE', 'REVIEW_UPDATE', 'REVIEW_DELETE',
